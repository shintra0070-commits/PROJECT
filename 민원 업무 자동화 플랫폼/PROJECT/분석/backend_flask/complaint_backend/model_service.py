def _clean_categories(result):
    categories = []
    for value in str(result).replace("\n", ",").split(","):
        label = value.strip().strip("`*[]()'\"")
        if label in ALLOWED_CATEGORIES and label not in categories:
            categories.append(label)
    if not categories:
        raise ValueError(f"허용되지 않은 부서 분류 결과입니다: {result!r}")
    return categories


