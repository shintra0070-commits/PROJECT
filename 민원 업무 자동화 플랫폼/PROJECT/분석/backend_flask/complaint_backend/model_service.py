# 3. 공통 정규식/유틸리티
SEPARATOR_REGEX = r"[\s\.,!?~\-_\*\+=\|/\\()\[\]{}:;\"'`@#$%^&]*"
REMOVE_SEPARATOR_REGEX = r"[\s\.,!?~\-_\*\+=\|/\\()\[\]{}:;\"'`0-9@#$%^&]+"


def contains_pattern(pattern: str, raw: str, norm: str) -> bool:
    return bool(re.search(pattern, raw, re.IGNORECASE) or re.search(pattern, norm, re.IGNORECASE))


def contains_any_pattern(patterns, raw: str, norm: str) -> bool:
    return any(contains_pattern(pattern, raw, norm) for pattern in patterns)


# 호환용 한글 자모(ㄴㅣ, ㅇㅐ, ㅂㅣ 등)를 완성형 한글로 조합합니다.
# 예: ㄴㅣㅇㅐㅂㅣ -> 니애비, ㅂㅕㅇㅅㅣㄴ -> 병신
CHOSEONG_LIST = list("ㄱㄲㄴㄷㄸㄹㅁㅂㅃㅅㅆㅇㅈㅉㅊㅋㅌㅍㅎ")
JUNGSEONG_LIST = list("ㅏㅐㅑㅒㅓㅔㅕㅖㅗㅘㅙㅚㅛㅜㅝㅞㅟㅠㅡㅢㅣ")
JONGSEONG_LIST = [
    "", "ㄱ", "ㄲ", "ㄳ", "ㄴ", "ㄵ", "ㄶ", "ㄷ", "ㄹ", "ㄺ",
    "ㄻ", "ㄼ", "ㄽ", "ㄾ", "ㄿ", "ㅀ", "ㅁ", "ㅂ", "ㅄ", "ㅅ",
    "ㅆ", "ㅇ", "ㅈ", "ㅊ", "ㅋ", "ㅌ", "ㅍ", "ㅎ",
]


def compose_compatibility_jamo(text: str) -> str:
    """분리된 호환용 한글 자모를 가능한 범위에서 완성형 음절로 조합합니다."""
    chars = list(str(text))
    result = []
    index = 0

    while index < len(chars):
        current = chars[index]

        if (
            current in CHOSEONG_LIST
            and index + 1 < len(chars)
            and chars[index + 1] in JUNGSEONG_LIST
        ):
            choseong_index = CHOSEONG_LIST.index(current)
            jungseong_index = JUNGSEONG_LIST.index(chars[index + 1])
            index += 2
            jongseong_index = 0

            if index < len(chars) and chars[index] in JONGSEONG_LIST[1:]:
                candidate = chars[index]

                # 다음 자모가 모음이면 현재 자음은 다음 음절의 초성으로 사용합니다.
                starts_next_syllable = (
                    candidate in CHOSEONG_LIST
                    and index + 1 < len(chars)
                    and chars[index + 1] in JUNGSEONG_LIST
                )

                if not starts_next_syllable:
                    jongseong_index = JONGSEONG_LIST.index(candidate)
                    index += 1

            syllable_code = (
                0xAC00
                + (choseong_index * 21 + jungseong_index) * 28
                + jongseong_index
            )
            result.append(chr(syllable_code))
            continue

        result.append(current)
        index += 1

    return "".join(result)


def restore_attached_profanity_shorthand(text: str) -> str:
    """
    자모 조합 과정에서 앞 음절의 받침으로 붙은 욕설 초성을 다시 분리합니다.

    예:
    - 엄맛ㅂ -> 엄마ㅅㅂ
    - 애빕ㅅ -> 애비ㅂㅅ
    """
    known_pairs = {"ㅅㅂ", "ㅆㅂ", "ㅂㅅ", "ㅈㄹ", "ㅅㄲ"}
    result = []
    index = 0

    while index < len(text):
        current = text[index]

        if (
            "가" <= current <= "힣"
            and index + 1 < len(text)
            and text[index + 1] in CHOSEONG_LIST
        ):
            syllable_index = ord(current) - 0xAC00
            jongseong_index = syllable_index % 28

            if jongseong_index > 0:
                jongseong = JONGSEONG_LIST[jongseong_index]
                shorthand = jongseong + text[index + 1]

                if shorthand in known_pairs:
                    base_syllable = chr(ord(current) - jongseong_index)
                    result.extend([base_syllable, jongseong, text[index + 1]])
                    index += 2
                    continue

        result.append(current)
        index += 1

    return "".join(result)


