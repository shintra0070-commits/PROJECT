def is_korean_keyboard_nonsense(text: str) -> bool:
    raw = str(text).strip()
    compact = re.sub(r"[^가-힣ㄱ-ㅎㅏ-ㅣa-zA-Z]", "", raw)
    if not compact:
        return False

    jamo_count = len(re.findall(r"[ㄱ-ㅎㅏ-ㅣ]", compact))
    syllable_count = len(re.findall(r"[가-힣]", compact))
    total_count = len(compact)

    if jamo_count == total_count:
        return True
    if jamo_count >= 4 and syllable_count <= 2 and jamo_count / total_count >= 0.60:
        return True
    return False


