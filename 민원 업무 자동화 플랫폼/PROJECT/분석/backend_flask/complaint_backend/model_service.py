def build_context_model_text(text) -> str:
    """원문 문맥과 욕설 정규화 결과를 함께 모델 입력으로 사용합니다."""
    raw = unicodedata.normalize("NFC", str(text)).lower()
    spaced = re.sub(r"[^가-힣ㄱ-ㅎㅏ-ㅣa-zA-Z0-9]+", " ", raw)
    spaced = re.sub(r"\s+", " ", spaced).strip()
    norm = normalize_text(raw)
    return f"{spaced} __normalized__ {norm}"


def normalize_context_label(value) -> Optional[str]:
    label = str(value).strip().upper()
    alias_map = {
        "0": "NORMAL", "NORMAL": "NORMAL", "정상": "NORMAL",
        "1": "WARNING", "WARNING": "WARNING", "경고": "WARNING", "욕설": "WARNING",
        "2": "NONSENSE", "NONSENSE": "NONSENSE", "무의미": "NONSENSE",
    }
    return alias_map.get(label)


def create_context_pipeline():
    if Pipeline is None:
        raise ImportError(
            "문맥 학습 모델을 사용하려면 scikit-learn과 joblib이 필요합니다. "
            "pip install scikit-learn joblib"
        )

    features = FeatureUnion([
        (
            "char",
            TfidfVectorizer(
                analyzer="char_wb",
                ngram_range=(2, 5),
                min_df=1,
                max_features=160000,
                sublinear_tf=True,
            ),
        ),
        (
            "word",
            TfidfVectorizer(
                analyzer="word",
                ngram_range=(1, 2),
                min_df=1,
                max_features=70000,
                sublinear_tf=True,
            ),
        ),
    ])

    return Pipeline([
        ("features", features),
        (
            "classifier",
            LogisticRegression(
                max_iter=2000,
                class_weight="balanced",
                C=4.0,
                solver="saga",
                random_state=42,
            ),
        ),
    ])


def train_context_model(
    csv_path,
    text_column="content",
    label_column="label_name",
    output_path=CONTEXT_MODEL_PATH,
    split_column=None,
    seed_repeat=8,
):
    """
    수정 완료된 정답 라벨 CSV로 문맥 모델을 학습하고 저장합니다.

    권장 컬럼
    - content 또는 input_sentence: 민원 원문
    - label_name: NORMAL / WARNING / NONSENSE
    - split(선택): train / valid / test

    주의: 기존 모델이 자동 출력한 결과를 그대로 정답으로 사용하면 오분류도 함께 학습합니다.
    사람이 검수하여 수정한 라벨 데이터를 사용해야 합니다.
    """
    if joblib is None:
        raise ImportError(
            "문맥 학습 모델을 사용하려면 scikit-learn과 joblib이 필요합니다. "
            "pip install scikit-learn joblib"
        )

    data = pd.read_csv(csv_path, encoding="utf-8-sig")

    if text_column not in data.columns:
        alternatives = [c for c in ("content", "input_sentence", "text", "원본민원") if c in data.columns]
        if not alternatives:
            raise KeyError(f"텍스트 컬럼을 찾지 못했습니다: {text_column}")
        text_column = alternatives[0]

    if label_column not in data.columns:
        alternatives = [c for c in ("label_name", "label", "llm_output", "필터링 결과") if c in data.columns]
        if not alternatives:
            raise KeyError(f"라벨 컬럼을 찾지 못했습니다: {label_column}")
        label_column = alternatives[0]

    data = data[[text_column, label_column] + ([split_column] if split_column and split_column in data.columns else [])].copy()
    data = data.dropna(subset=[text_column, label_column])
    data["_label"] = data[label_column].map(normalize_context_label)
    data = data.dropna(subset=["_label"])
    data[text_column] = data[text_column].astype(str).str.strip()
    data = data[data[text_column].str.len() > 0]
    data = data.drop_duplicates(subset=[text_column, "_label"])

    # 검수에서 발견된 경계 사례를 소량 반복해 학습 데이터에 추가합니다.
    seed_rows = []
    for sentence, label in CONTEXT_SEED_EXAMPLES:
        for _ in range(max(1, int(seed_repeat))):
            seed_row = {text_column: sentence, "_label": label}
            if split_column and split_column in data.columns:
                seed_row[split_column] = "train"
            seed_rows.append(seed_row)
    data = pd.concat([data, pd.DataFrame(seed_rows)], ignore_index=True)

    if split_column and split_column in data.columns:
        split_values = data[split_column].astype(str).str.lower()
        train_mask = split_values.isin({"train", "training"})
        eval_mask = split_values.isin({"valid", "validation", "val", "test"})
        train_df = data[train_mask].copy()
        eval_df = data[eval_mask].copy()
        if train_df.empty:
            raise ValueError("split 컬럼에서 train 데이터를 찾지 못했습니다.")
    else:
        train_df, eval_df = train_test_split(
            data,
            test_size=0.2,
            random_state=42,
            stratify=data["_label"],
        )

    model = create_context_pipeline()
    model.fit(
        train_df[text_column].map(build_context_model_text),
        train_df["_label"],
    )

    if not eval_df.empty:
        actual = eval_df["_label"]
        predicted = model.predict(eval_df[text_column].map(build_context_model_text))
        print("[문맥 모델 평가]")
        print(classification_report(actual, predicted, digits=4, zero_division=0))
        print("[혼동행렬: NORMAL, WARNING, NONSENSE]")
        print(confusion_matrix(actual, predicted, labels=["NORMAL", "WARNING", "NONSENSE"]))

    output_path = Path(output_path)
    joblib.dump(
        {
            "model": model,
            "labels": ["NORMAL", "WARNING", "NONSENSE"],
            "text_column": text_column,
            "label_column": label_column,
        },
        output_path,
    )
    print(f"문맥 모델 저장 완료: {output_path.resolve()}")
    return model


def get_context_model():
    global context_model

    if not USE_CONTEXT_MODEL or joblib is None:
        return None

    if context_model is None:
        if not CONTEXT_MODEL_PATH.exists():
            return None
        saved = joblib.load(CONTEXT_MODEL_PATH)
        context_model = saved["model"] if isinstance(saved, dict) else saved

    return context_model


def context_model_classify(text) -> Tuple[Optional[str], float]:
    model = get_context_model()
    if model is None:
        return None, 0.0

    model_text = build_context_model_text(text)
    probabilities = model.predict_proba([model_text])[0]
    classes = model.classes_
    best_index = int(probabilities.argmax())
    return str(classes[best_index]), float(probabilities[best_index])



