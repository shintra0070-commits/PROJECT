def is_normal_family_reference(raw: str, norm: str) -> bool:
    """본인 가족의 불편·피해·의견 전달 문맥만 NORMAL 예외로 인정합니다."""
    if not is_complete_sentence_form(raw):
        return False

    if not contains_any_pattern(FAMILY_NORMAL_PATTERNS, raw, norm):
        return False

    # 가족 공격 문맥이 하나라도 있으면 정상 예외를 적용하지 않습니다.
    if is_family_attack_context(raw, norm):
        return False

    if contains_any_pattern(FAMILY_DIRECT_TARGET_PATTERNS, raw, norm):
        return False

    if contains_any_pattern(FAMILY_ABUSIVE_CONTEXT_PATTERNS, raw, norm):
        return False

    explicit_warning_words = (
        STRONG_PROFANITY_WORDS
        + BUG_CHUNG_INSULT_WORDS
        + DISMISSIVE_INSULT_WORDS
        + BAD_WORDS
    )
    if any(word in norm for word in explicit_warning_words):
        return False

    return True


